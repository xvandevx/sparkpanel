/** Что лежит в JWT и, после проверки гардом, в req.user. */
export interface JwtPayload {
  id: number;
  email: string;
  /** Главный администратор: по этому флагу сервер пускает в управление панелью */
  isRoot: boolean;
  /**
   * Откуда пришла правка, если не из браузера: «MCP «Claude Code»», «API «1С»».
   * Такой токен выпускает только сам сервер — на минуту, для маршрутов панели
   * от имени ассистента или ключа API (`common/panel-client.ts`); журнал
   * дописывает это к автору
   */
  via?: string;
}
