/** Тело запроса на создание: шаблон меты отправляем только динамической странице. */
function toCreateBody(parentId, def) {
  const kind = def.kind ?? 'static';
  return {
    parentId,
    code: def.code,
    name: def.name,
    kind,
    isActive: def.isActive ?? true,
    content: def.content ?? null,
    meta: def.meta,
    ...(kind === 'dynamic' && def.metaTemplate ? { metaTemplate: def.metaTemplate } : {}),
  };
}

const findChild = (pages, parentId, code) =>
  pages.find((page) => page.parentId === parentId && page.code === code);

export default async function seed() {
  let pages = await get('/pages');
  const stats = { created: 0, existing: 0 };

  const home = pages.find((page) => page.isHome);
  if (!home) throw new Error('Главная страница не найдена');

  const catalog = findChild(pages, home.id, 'catalog');
  const news = findChild(pages, home.id, 'news');
  if (!catalog) log(SECTION, 'нет страницы «Каталог» (catalog) — её подразделы пропущены');
  if (!news) log(SECTION, 'нет страницы «Новости» (news) — новости пропущены');

  async function seedChildren(parent, defs, pathPrefix) {
    for (const def of defs) {
      const path = `${pathPrefix}/${def.code}`;
      let page = findChild(pages, parent.id, def.code);

      if (page) {
        stats.existing += 1;
      } else {
        try {
          page = await post('/pages', toCreateBody(parent.id, def));
          pages.push(page);
          stats.created += 1;
          log(SECTION, `+ ${path} — ${def.name}${page.isActive ? '' : ' (неактивна)'}`);
        } catch (error) {
          // 409: страницу с таким кодом успели создать параллельно — берём её
          if (error.status !== 409) throw error;
          pages = await get('/pages');
          page = findChild(pages, parent.id, def.code);
          if (!page) throw error;
          stats.existing += 1;
        }
      }

      if (def.children?.length) await seedChildren(page, def.children, path);
    }
  }

  await seedChildren(home, HOME_CHILDREN, '');
  if (catalog) await seedChildren(catalog, CATALOG_CHILDREN, '/catalog');
  if (news) await seedChildren(news, NEWS_CHILDREN, '/news');

  const total = (await get('/pages')).length;
  log(SECTION, `создано ${stats.created}, уже было ${stats.existing}, всего страниц ${total}`);
  return stats;
}
