export default async function seed() {
  const created = { types: 0, blocks: 0, elements: 0 };
  const structure = await get('/infoblocks');

  /** Код инфоблока уникален у пользователя целиком — ищем по всем типам. */
  const allBlocks = structure.flatMap((type) => type.blocks ?? []);

  for (const type of TYPES) {
    const { item: section, created: typeIsNew } = await ensure(
      structure,
      (row) => row.code === type.code,
      () =>
        post('/infoblocks/sections', {
          code: type.code,
          name: type.name,
          ...(type.description ? { description: type.description } : {}),
        }),
    );
    if (typeIsNew) {
      created.types += 1;
      structure.push({ ...section, blocks: [] });
    }
    log(SECTION, `тип ${typeIsNew ? 'создан' : 'уже есть'}: ${section.code} «${section.name}»`);

    for (const block of type.blocks) {
      const { item: infoblock, created: blockIsNew } = await ensure(
        allBlocks,
        (row) => row.code === block.code,
        () =>
          post('/infoblocks/blocks', {
            sectionId: section.id,
            code: block.code,
            name: block.name,
            ...(block.elementName ? { elementName: block.elementName } : {}),
            ...(block.description ? { description: block.description } : {}),
            isActive: true,
          }),
      );
      if (blockIsNew) {
        created.blocks += 1;
        allBlocks.push(infoblock);
      }
      if (infoblock.sectionId !== section.id) {
        log(SECTION, `  инфоблок ${infoblock.code} лежит в другом типе (#${infoblock.sectionId}) — не переносим`);
      }

      const elements = await get(`/infoblocks/blocks/${infoblock.id}/elements`);
      let blockCreated = 0;
      for (const element of block.elements) {
        const { created: elementIsNew, item } = await ensure(
          elements,
          (row) => row.code === element.code,
          () =>
            post(`/infoblocks/blocks/${infoblock.id}/elements`, {
              code: element.code,
              name: element.name,
              preview: element.preview ?? null,
              content: element.content ?? null,
              ...(element.date ? { date: element.date } : {}),
              isActive: element.isActive ?? true,
            }),
        );
        if (elementIsNew) {
          blockCreated += 1;
          elements.push(item);
        }
      }
      created.elements += blockCreated;
      log(
        SECTION,
        `  инфоблок ${blockIsNew ? 'создан' : 'уже есть'}: ${infoblock.code} «${infoblock.name}» — ` +
          `записей добавлено ${blockCreated}, всего ${elements.length}`,
      );
    }
  }

  const total = created.types + created.blocks + created.elements;
  log(
    SECTION,
    `создано: типов ${created.types}, инфоблоков ${created.blocks}, записей ${created.elements} (всего ${total})`,
  );
  return { created: total, ...created };
}
