/**
 * Api раздела — всё, что редактору нужно знать о том, где лежат записи.
 * Больше раздел о данных не рассказывает ничего: загрузку, состояние,
 * перечитывание после сохранения, ошибки и историю ведёт сам редактор.
 * Журнала здесь нет намеренно: он общий на всю панель и читается по `key`
 * (`logic/contentEditor/listHistory.ts`).
 *
 * Методы работают со строковыми ключами записи — теми же, что стоят в адресе
 * страницы и в журнале (`2`, `form-1`, `element-3`). Перевод в номер (или в путь
 * с владельцем) — дело самого Api раздела: это единственное место, где такие
 * подробности остались.
 */
export interface EditorApi<T = unknown> {
  /** Ключ списка: он же ключ ячейки в сторе и ключ настроек списка */
  key: string;
  /** Весь список записей */
  list: () => Promise<T[]>;
  create: (payload: Record<string, unknown>) => Promise<T>;
  update: (id: string, payload: Record<string, unknown>) => Promise<T>;
  /** Не задано — удалять записи нельзя (так у «Пользователей») */
  remove?: (id: string) => Promise<unknown>;
}

/** Ключ записи, которую ещё не сохранили: номер ей выдаст сервер. */
export const NEW_RECORD_ID = 'будет присвоен при сохранении';
