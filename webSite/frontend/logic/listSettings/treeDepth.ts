/**
 * Дерево ли список. Своего поля нет — его заменил предел вложенности
 * (галочка «Древовидная структура» в окне настроек пишет его же):
 * один уровень — плоский список, больше или без ограничения (null) — дерево.
 * То же правило держит бэкенд (`infoblocks/settings/tree-depth.ts`).
 */
export const isTreeDepth = (maxDepth: number | null): boolean => maxDepth !== 1;
