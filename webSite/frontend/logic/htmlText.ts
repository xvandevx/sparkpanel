/**
 * Текст из разметки: без тегов, пробелы схлопнуты. Так HTML-свойство видно
 * в ячейке таблицы, и по этому же тексту его ищет фильтр — иначе подстрока
 * находилась бы в названиях тегов, которых человек не видит.
 */
export const htmlText = (html: string): string =>
  html.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
